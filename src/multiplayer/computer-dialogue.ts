export type ComputerDialogueEvent=keyof typeof COMPUTER_DIALOGUE;

/** Dialogue randomness is independent of the match's combat/question seed. */
export class ComputerDialogue{
 private bags=new Map<ComputerDialogueEvent,number[]>();
 private recent:string[]=[];
 private randomState:number;
 constructor(seed:number){this.randomState=(seed^0xa53c91e7)>>>0||1;}
 private random(){let value=this.randomState;value^=value<<13;value^=value>>>17;value^=value<<5;this.randomState=value>>>0;return this.randomState/0x100000000;}
 next(event:ComputerDialogueEvent):string{
  const lines=COMPUTER_DIALOGUE[event];let bag=this.bags.get(event);
  if(!bag?.length){
   bag=lines.map((_,i)=>i);
   for(let i=bag.length-1;i>0;i--){const j=Math.floor(this.random()*(i+1));[bag[i],bag[j]]=[bag[j],bag[i]];}
   this.bags.set(event,bag);
  }
  const available=bag.findIndex(i=>!this.recent.includes(lines[i])),index=bag.splice(available<0?0:available,1)[0],phrase=lines[index];
  this.recent.push(phrase);if(this.recent.length>6)this.recent.shift();return phrase;
 }
}
